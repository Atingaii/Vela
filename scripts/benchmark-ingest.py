"""Exercise bounded real-CLI ingestion across independent synthetic input axes.

The default smoke suite covers 10 sessions, a 1 MB file, and 10k raw messages.
`--suite matrix` adds 100/1000 sessions, 10/50/500 MB files and 100k messages.
These axes are not multiplied: a 1000-file case has ten messages per file.
Input files are generated by streaming writes, and removed with their isolated
stores. Reported timing is explicit RPC refresh, not FSEvents-to-UI or cold start.
The 60-file selection cap and tail retention are measured, never presented as
complete observation of all generated input. No full Observe hard gate is scored.
"""
import argparse
import datetime
import hashlib
import importlib.util
import json
import os
import pathlib
import sqlite3
import statistics
import subprocess
import tempfile
import threading
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('vela_read_benchmark', ROOT / 'scripts/benchmark-read.py')
READ = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(READ)


def generate(directory, case):
    provider = directory / 'claude'
    provider.mkdir(parents=True)
    project = directory.parent / 'project'
    project.mkdir()
    total_bytes = total_messages = 0
    digest = hashlib.sha256()
    count = case.get('sessions', 1)
    for index in range(count):
        path = provider / f'synthetic-{index:04}.jsonl'
        written = messages = 0
        with path.open('wb') as output:
            while True:
                content = f'Synthetic verification record {index}-{messages}. ' + ('bounded context ' * 35)
                row = dict(type='user' if messages % 2 == 0 else 'assistant', uuid=f'message-{messages:07}',
                           timestamp='2026-09-12T00:00:00Z', sessionId=f'fixture-{index:04}',
                           message=dict(role='user' if messages % 2 == 0 else 'assistant', content=content))
                if messages == 0:
                    row.update(cwd=str(project), gitBranch='fixture')
                data = (json.dumps(row, separators=(',', ':')) + '\n').encode()
                output.write(data)
                digest.update(data)
                written += len(data)
                messages += 1
                if 'megabytes' in case:
                    if written >= case['megabytes'] * 1_000_000:
                        break
                elif messages >= case.get('messages', 10):
                    break
        # Deterministic recency avoids ambiguous selection at the 60-file cap.
        os.utime(path, (1_789_171_200 + index, 1_789_171_200 + index))
        total_bytes += written
        total_messages += messages
    return dict(sourceFiles=count, sourceBytes=total_bytes, rawMessages=total_messages,
                fixtureSHA256=digest.hexdigest(), sourceProvider='claude synthetic documented JSONL subset',
                selectedFilesExpected=min(count, 60), completeInputExpected='sessions' in case and count <= 60)


def sample(binary, sources, store):
    env = dict(os.environ, VELA_HOME=str(store), VELA_SESSION_ROOT=str(sources), VELA_DISABLE_DISCOVERY='1')
    client = READ.RPC(binary, store, env)
    stop = threading.Event()
    rss_values = []

    def read_rss():
        result = subprocess.run(['/bin/ps', '-o', 'rss=', '-p', str(client.process.pid)],
                                text=True, capture_output=True, timeout=3)
        if result.returncode == 0 and result.stdout.strip():
            rss_values.append(int(result.stdout.strip()))

    def monitor():
        while not stop.wait(0.05):
            read_rss()

    monitor_thread = None
    try:
        version = client.call('system.version', {})['version']
        read_rss()
        monitor_thread = threading.Thread(target=monitor, daemon=True)
        monitor_thread.start()
        begin = time.perf_counter()
        refreshed = client.call('sessions.refresh', {})
        elapsed = (time.perf_counter() - begin) * 1000
        read_rss()
        stop.set()
        monitor_thread.join(timeout=5)
        # Read stored records independently; summaries deliberately omit messages.
        with sqlite3.connect(store / 'vela.sqlite3') as database:
            records = [json.loads(row[0]) for row in database.execute("SELECT json FROM objects WHERE kind='session'")]
        retained = sum(len(item.get('messages', [])) for item in records)
        truncated = sum(bool(item.get('historyTruncated') or item.get('messagesTruncated')) for item in records)
        return dict(cliVersion=version, refreshElapsedMs=round(elapsed, 3), sourceFilesChecked=refreshed['sourceFilesChecked'],
                    sourcesUpdated=refreshed['sourcesUpdated'], indexedSessions=len(records), retainedMessages=retained,
                    truncatedSessions=truncated, historyFullyIndexed=refreshed['historyFullyIndexed'],
                    perSessionFullyIndexed=sum(item.get('historyFullyIndexed') is True for item in records),
                    maximumRetainedMessages=max((len(item.get('messages', [])) for item in records), default=0),
                    initialFileLimit=refreshed['initialFileLimit'], initialTailBytes=refreshed['initialTailBytes'],
                    helperRssKiB=dict(baseline=rss_values[0], sampledMaximum=max(rss_values), samples=rss_values,
                                      cadenceMs=50, meaning='Sampled helper RSS; short peaks and other processes are not covered'),
                    diagnostics=[{key: value for key, value in item.items() if key != 'path'} for item in refreshed['diagnostics']])
    finally:
        stop.set()
        if monitor_thread:
            monitor_thread.join(timeout=5)
        client.close()


def run_case(args, binary, case):
    with tempfile.TemporaryDirectory(prefix='vela-benchmark-ingest-') as temporary:
        directory = pathlib.Path(temporary)
        sources = directory / 'sources'
        begin = time.perf_counter()
        fixture = generate(sources, case)
        generation_ms = (time.perf_counter() - begin) * 1000
        measurements = [sample(binary, sources, directory / f'store-{index}') for index in range(args.samples)]
        for measurement in measurements:
            assert measurement['sourceFilesChecked'] == fixture['selectedFilesExpected'], measurement
            assert measurement['indexedSessions'] == fixture['selectedFilesExpected'], measurement
            assert measurement['maximumRetainedMessages'] <= 1000, measurement
            assert measurement['historyFullyIndexed'] is False, measurement
            assert not any(item.get('severity') == 'warning' for item in measurement['diagnostics']), measurement
            if 'sessions' in case:
                assert measurement['retainedMessages'] == fixture['selectedFilesExpected'] * 10, measurement
                assert measurement['perSessionFullyIndexed'] == fixture['selectedFilesExpected'], measurement
            else:
                assert 0 < measurement['retainedMessages'] < fixture['rawMessages'], measurement
                assert measurement['truncatedSessions'] == 1, measurement
        times = [measurement['refreshElapsedMs'] for measurement in measurements]
        return dict(case=case, input=fixture, generationMs=round(generation_ms, 3),
                    samples=measurements, medianRefreshMs=round(statistics.median(times), 3), maximumRefreshMs=max(times),
                    correctnessPassed=True, completeFixtureInputRetained=fixture['sourceFiles'] <= 60 and 'sessions' in case,
                    timingThreshold=None, performanceGate='not decided by this benchmark')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=pathlib.Path, default=ROOT / '.build/release/vela')
    parser.add_argument('--suite', choices=['smoke', 'matrix'], default='smoke')
    parser.add_argument('--samples', type=int, default=3)
    parser.add_argument('--output', type=pathlib.Path)
    args = parser.parse_args()
    if args.samples < 1:
        parser.error('Use at least one sample; fewer than 20 samples do not establish a p95 distribution.')
    binary = args.binary.resolve(strict=True)
    cases = ([dict(axis='sessions', sessions=value) for value in [10, 100, 1000]] +
             [dict(axis='file_size', megabytes=value) for value in [1, 10, 50, 500]] +
             [dict(axis='messages', messages=value) for value in [10000, 100000]])
    if args.suite == 'smoke':
        cases = [cases[0], cases[3], cases[7]]
    report = dict(format='vela-ingest-benchmark-v1', timestampUTC=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                  environment=READ.metadata(binary), suite=args.suite, samplesPerCase=args.samples,
                  units='MB = 1,000,000 bytes; tail bytes and RSS KiB reported separately',
                  cache='Fresh store/helper for each sample, shared generated sources; OS caches not evicted',
                  metric='Explicit sessions.refresh RPC elapsed, including 50 ms RSS sampling overhead',
                  limits='Single synthetic provider; no full backfill, watcher-to-UI latency, real agent concurrency or cold launch claim',
                  results=[run_case(args, binary, case) for case in cases])
    text = json.dumps(report, indent=2) + '\n'
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(text, end='')


if __name__ == '__main__':
    main()
