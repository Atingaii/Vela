  function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  function interpolate(template, params) {
    if (!template || !params) return template;
    return String(template).replace(/\{([a-zA-Z0-9_-]+)\}/g, (match, paramKey) => {
      if (Object.prototype.hasOwnProperty.call(params, paramKey)) {
        return params[paramKey] !== undefined && params[paramKey] !== null ? String(params[paramKey]) : '';
      }
      return match;
    });
  }

  function t(key, params) {
    if (!key) return '';
    const targetDict = DICTIONARY[currentLocale];
    const hasTarget = Boolean(targetDict && Object.prototype.hasOwnProperty.call(targetDict, key));
    let val;

    if (hasTarget) {
      val = targetDict[key];
    } else {
      missingKeys.add(key);
      const fallbackDict = DICTIONARY[DEFAULT_LOCALE];
      if (fallbackDict && Object.prototype.hasOwnProperty.call(fallbackDict, key)) {
        val = fallbackDict[key];
      } else {
        val = key;
      }
    }

    // Record missing key if missing in English catalog even when running under zh-CN fallback
    const enDict = DICTIONARY['en'];
    if (!enDict || !Object.prototype.hasOwnProperty.call(enDict, key)) {
      missingKeys.add(key);
    }

    if (params && typeof params === 'object') {
      return interpolate(val, params);
    }
    return val;
  }

  function tHtml(key, params, tagName = 'span') {
    const text = t(key, params);
    const escapedKey = escapeHtml(key);
    const tag = tagName || 'span';
    const paramsAttr = params ? ` data-i18n-params="${escapeHtml(JSON.stringify(params))}"` : '';
    return `<${tag} data-i18n="${escapedKey}"${paramsAttr}>${escapeHtml(text)}</${tag}>`;
  }

  function hasKey(key, locale) {
    const targetLocale = locale || currentLocale;
    const dict = DICTIONARY[targetLocale];
    return Boolean(dict && Object.prototype.hasOwnProperty.call(dict, key));
  }

  function getMissingKeys() {
    return Array.from(missingKeys);
  }

  function getLocale() {
    return currentLocale;
  }

  function parseParams(el) {
    const raw = el.getAttribute('data-i18n-params');
    if (!raw) return null;
    try {
      return JSON.parse(raw);
    } catch {
      return null;
    }
  }

  function setElementDescriptor(el, descriptorOrText) {
    if (!el || el.nodeType !== 1) return;
    if (descriptorOrText && typeof descriptorOrText === 'object' && descriptorOrText.key) {
      el.setAttribute('data-i18n', descriptorOrText.key);
      if (descriptorOrText.params) {
        el.setAttribute('data-i18n-params', JSON.stringify(descriptorOrText.params));
      } else {
        el.removeAttribute('data-i18n-params');
      }
      const nextText = t(descriptorOrText.key, descriptorOrText.params);
      if (el.textContent !== nextText) {
        el.textContent = nextText;
      }
    } else {
      el.removeAttribute('data-i18n');
      el.removeAttribute('data-i18n-params');
      el.removeAttribute('data-i18n-title');
      el.removeAttribute('data-i18n-placeholder');
      el.removeAttribute('data-i18n-aria-label');
      const plainText = (descriptorOrText !== null && descriptorOrText !== undefined) ? String(descriptorOrText) : '';
      if (el.textContent !== plainText) {
        el.textContent = plainText;
      }
    }
  }

  function checkParity() {
    const zhKeys = Object.keys(DICTIONARY['zh-CN'] || {});
    const enDict = DICTIONARY['en'] || {};
    const missingInEn = zhKeys.filter(k => !Object.prototype.hasOwnProperty.call(enDict, k));
    const enKeys = Object.keys(enDict);
    const zhDict = DICTIONARY['zh-CN'] || {};
    const missingInZh = enKeys.filter(k => !Object.prototype.hasOwnProperty.call(zhDict, k));
    return { missingInEn, missingInZh, totalZh: zhKeys.length, totalEn: enKeys.length };
  }

  function applyNodeTranslations(node) {
    if (!node || node.nodeType !== 1) return;

    if (node.hasAttribute('data-i18n')) {
      const key = node.getAttribute('data-i18n');
      const params = parseParams(node);
      const nextVal = t(key, params);
      if (node.textContent !== nextVal) {
        node.textContent = nextVal;
      }
    }
    if (node.hasAttribute('data-i18n-title')) {
      const key = node.getAttribute('data-i18n-title');
      const params = parseParams(node);
      const nextVal = t(key, params);
      if (node.title !== nextVal) {
        node.title = nextVal;
      }
    }
    if (node.hasAttribute('data-i18n-placeholder')) {
      const key = node.getAttribute('data-i18n-placeholder');
      const params = parseParams(node);
      const nextVal = t(key, params);
      if (node.placeholder !== nextVal) {
        node.placeholder = nextVal;
      }
    }
    if (node.hasAttribute('data-i18n-aria-label')) {
      const key = node.getAttribute('data-i18n-aria-label');
      const params = parseParams(node);
      const nextVal = t(key, params);
      if (node.getAttribute('aria-label') !== nextVal) {
        node.setAttribute('aria-label', nextVal);
      }
    }
  }

  function applyTranslations(rootElement) {
    const root = rootElement || document;
    if (root.nodeType === 1) {
      applyNodeTranslations(root);
    }
    const elements = root.querySelectorAll ? root.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-placeholder], [data-i18n-aria-label]') : [];
    for (let i = 0; i < elements.length; i++) {
      applyNodeTranslations(elements[i]);
    }
  }

  function setLocale(newLocale) {
    if (!SUPPORTED_LOCALES.includes(newLocale)) {
      return false;
    }
    if (currentLocale === newLocale) {
      return true;
    }
    currentLocale = newLocale;
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = newLocale;
    }
    applyTranslations(document);
    try {
      window.dispatchEvent(new CustomEvent('vela:localeApplied', { detail: { locale: newLocale } }));
    } catch {}
    return true;
  }

  function formatTime(isoStr, localeOverride) {
    if (!isoStr) return '-';
    try {
      const d = new Date(isoStr);
      if (isNaN(d.getTime())) return '-';
      const loc = (localeOverride || currentLocale) === 'en' ? 'en-US' : 'zh-CN';
      return d.toLocaleString(loc, {
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit'
      });
    } catch {
      return '-';
    }
  }

  function formatNumber(num, localeOverride) {
    if (typeof num !== 'number' || !Number.isFinite(num)) return '-';
    const loc = (localeOverride || currentLocale) === 'en' ? 'en-US' : 'zh-CN';
    return num.toLocaleString(loc);
  }

  // MutationObserver for explicitly marked dynamically inserted bindings
  let observer = null;
  function initObserver() {
    if (typeof MutationObserver === 'undefined' || !document.body) return;
    observer = new MutationObserver((mutations) => {
      for (let m = 0; m < mutations.length; m++) {
        const mut = mutations[m];
        if (mut.type === 'childList') {
          for (let i = 0; i < mut.addedNodes.length; i++) {
            const added = mut.addedNodes[i];
            if (added.nodeType === 1) {
              applyNodeTranslations(added);
              const children = added.querySelectorAll ? added.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-placeholder], [data-i18n-aria-label]') : [];
              for (let c = 0; c < children.length; c++) {
                applyNodeTranslations(children[c]);
              }
            }
          }
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', () => {
        applyTranslations(document);
        initObserver();
      });
    } else {
      applyTranslations(document);
      initObserver();
    }
  }

  // Public API
  window.VelaI18n = {
    SUPPORTED_LOCALES,
    DEFAULT_LOCALE,
    DICTIONARY,
    t,
    tHtml,
    hasKey,
    getMissingKeys,
    getLocale,
    setLocale,
    applyTranslations,
    setElementDescriptor,
    checkParity,
    formatTime,
    formatNumber
  };
